"""Interface languages. English is the source language; Spanish is a translation table."""

from __future__ import annotations

import re

LANGUAGES = [("en", "English"), ("es", "Español")]
_lang = "en"


def set_language(code: str):
    global _lang
    _lang = code if code in ("en", "es") else "en"


def language() -> str:
    return _lang


def t(text: str, **values) -> str:
    """Translate an interface string. Unknown strings (names typed by the user) pass through.

    The interface is set entirely in lowercase, so the result is lowercased here, names included.
    """
    if _lang == "es":
        text = ES.get(text, text)
    return (text.format(**values) if values else text).lower()


def t_name(name: str) -> str:
    """Translate an automatic name ("My light", "Light 2", "Scene 3"); custom names pass through."""
    if _lang == "es":
        m = re.fullmatch(r"(Light|Scene) (\d+)", name or "")
        if m:
            return f"{'luz' if m.group(1) == 'Light' else 'escena'} {m.group(2)}"
    return t(name or "")


